@bot.message_handler(commands=["start"])
def start(message):
    bot.reply_to(
        message,
        "سلام! ❤️\n"
        "متن فارسی یا انگلیسی خودت رو بفرست "
        "تا به فونت‌های فانتزی تبدیلش کنم."
    )

@bot.message_handler(content_types=["text"])
def convert_text(message):
    text = message.text

    if not text:
        return

    results = []
    for i, font in enumerate(fonts, start=1):
        results.append(f"فونت {i}:\n{text.translate(font)}")

    bot.reply_to(message, "\n\n".join(results))

def run_bot():
    bot.infinity_polling(skip_pending=True, timeout=30)

if __name__ == "__main__":
    threading.Thread(target=run_bot, daemon=True).start()
    port = int(os.environ.get("PORT", 10000))
    app.run(host="0.0.0.0", port=port)
